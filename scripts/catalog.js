/**
 * Generates the skill catalog of the docs (docs/reference/skills.md) and the map for language
 * models (docs/public/llms.txt, https://llmstxt.org) from the frontmatter of every skill, so
 * neither can drift from skills/.
 *
 * Usage: pnpm catalog [--check]   (`--check` exits 1 instead of writing when a file is stale)
 */

const fs = require('node:fs');
const path = require('node:path');

const { listSkills } = require('../src/link.js');
const { parseFrontmatter } = require('./frontmatter.js');
const pkg = require('../package.json');
const packs = require('../src/packs.json');

const ROOT = path.join(__dirname, '..');
const SKILLS_DIR = path.join(ROOT, 'skills');
const CATALOG = path.join(ROOT, 'docs', 'reference', 'skills.md');
const LLMS = path.join(ROOT, 'docs', 'public', 'llms.txt');
// The project is called alexiskills; the repository and the npm package keep the metaskills name.
const NAME = 'alexiskills';
const REPOSITORY = 'https://github.com/Alexis-Technologies/metaskills';

const indexPacks = (list) => {
  const index = new Map();
  const packNames = Object.keys(list);
  for (let i = 0; i < packNames.length; i++) {
    const pack = packNames[i];
    for (let j = 0; j < list[pack].length; j++) index.set(list[pack][j], pack);
  }
  return index;
};

const readSkills = (source, list = packs) => {
  const index = indexPacks(list);
  const skills = [];
  const names = listSkills(source);
  for (let i = 0; i < names.length; i++) {
    const name = names[i];
    const pack = index.get(name);
    if (!pack) throw new Error(`${name} is in no pack of src/packs.json`);
    const text = fs.readFileSync(path.join(source, name, 'SKILL.md'), 'utf8');
    const { description } = parseFrontmatter(text).fields;
    skills.push({ name, pack, description });
  }
  return skills;
};

const escapeCell = (text) =>
  text.replaceAll('|', '\\|').replaceAll('<', '&lt;').replaceAll('{', '&#123;');

const renderCatalog = (skills) => {
  const head = [
    '---',
    'title: Skills',
    `description: Every skill of ${NAME} and when an agent uses it.`,
    '---',
    '',
    '# Skills',
    '',
    '<!-- Generated by scripts/catalog.js from the frontmatter of skills/. Do not edit. -->',
    '',
    '| Skill | Pack | When an agent uses it |',
    '| --- | --- | --- |',
  ];
  const rows = skills.map(({ name, pack, description }) => {
    const url = `${REPOSITORY}/blob/main/skills/${name}/SKILL.md`;
    return `| [\`${name}\`](${url}) | \`${pack}\` | ${escapeCell(description)} |`;
  });
  return `${head.concat(rows).join('\n')}\n`;
};

const renderLlms = (skills) => {
  const head = [
    `# ${NAME}`,
    '',
    `> ${pkg.description}`,
    '',
    `- Package: ${pkg.name}`,
    `- Docs: ${pkg.homepage}`,
    `- Node.js: ${pkg.engines.node}`,
    `- License: ${pkg.license}`,
    '',
    '## Skills',
    '',
  ];
  const rows = skills.map(({ name, pack, description }) => {
    const url = `${REPOSITORY}/blob/main/skills/${name}/SKILL.md`;
    return `- [${name}](${url}) (${pack}): ${description}`;
  });
  return `${head.concat(rows).join('\n')}\n`;
};

const readIfExists = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '');

const main = () => {
  const isCheck = process.argv.includes('--check');
  const skills = readSkills(SKILLS_DIR);
  const outputs = [
    { file: CATALOG, content: renderCatalog(skills) },
    { file: LLMS, content: renderLlms(skills) },
  ];
  for (let i = 0; i < outputs.length; i++) {
    const { file, content } = outputs[i];
    const relative = path.relative(ROOT, file);
    if (readIfExists(file) === content) continue;
    if (isCheck) {
      console.error(`${relative} is stale. Run: pnpm catalog`);
      process.exitCode = 1;
      continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`Wrote ${relative}`);
  }
};

if (require.main === module) main();

module.exports = { readSkills, renderCatalog, renderLlms };
